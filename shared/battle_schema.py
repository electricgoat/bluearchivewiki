"""
Resolves integer enum values in battle data (LevelSkill timelines, LogicEffect rows) to their names.

The game serializes many enum fields as plain ints. battle_schema.json holds the declared field types of the game's
battle DAO classes and the enums they use (generated by scripts/build_battle_schema.py from a game code dump),
so values get resolved by following those types from each object's $type down.
Values an enum does not name (such as combined flags) are left as ints.
"""
import functools
import json
import os

with open(os.path.join(os.path.dirname(__file__), 'battle_schema.json'), encoding='utf-8') as f:
    SCHEMA = json.load(f)
ENUMS: dict[str, dict[str, str]] = SCHEMA['enums']


def type_name(node: dict) -> str:
    return node.get('$type', '').split(',')[0].rsplit('.', 1)[-1]


@functools.cache
def fields_of(class_name: str | None) -> dict[str, str]:
    """Declared types of enum and class fields, including inherited ones"""
    cls = SCHEMA['classes'].get(class_name)
    if cls is None: return {}
    return fields_of(cls.get('base')) | cls['fields']


def enum_value(enum: str, value):
    if isinstance(value, list): return [enum_value(enum, x) for x in value]
    if isinstance(value, bool) or not isinstance(value, int): return value
    return ENUMS[enum].get(str(value), value)


def resolve(node, class_name: str | None = None):
    """Resolves enum values in place, returns the node"""
    if isinstance(node, list):
        for item in node: resolve(item, class_name)
    elif isinstance(node, dict):
        fields = fields_of(type_name(node) or class_name)
        for key, value in node.items():
            field_type = fields.get(key)
            if field_type in ENUMS: node[key] = enum_value(field_type, value)
            elif isinstance(value, (dict, list)): resolve(value, field_type)
    return node
